#!/usr/bin/env python3
"""Gzip firmware/web/index.html into include/web_index.h (PROGMEM byte array)."""
import gzip, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / 'firmware'
src = (root / 'web' / 'index.html').read_bytes()
gz = gzip.compress(src, 9)
out = ['// generated by dev/embed_web.py - do not edit', '#pragma once', '#include <pgmspace.h>',
       f'#define WEB_INDEX_LEN {len(gz)}', 'static const uint8_t WEB_INDEX_GZ[] PROGMEM = {']
out += [','.join(str(b) for b in gz[i:i+40]) + ',' for i in range(0, len(gz), 40)]
out += ['};']
(root / 'include' / 'web_index.h').write_text('\n'.join(out) + '\n')
print(f'index.html {len(src)} bytes -> {len(gz)} bytes gzip')
