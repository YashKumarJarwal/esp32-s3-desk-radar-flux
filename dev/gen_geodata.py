#!/usr/bin/env python3
"""Generate firmware/include/geo_data.h from OurAirports + Natural Earth files in dev/geodata (run with python3 -I)."""
import csv, json, sys, pathlib, math
src = pathlib.Path(sys.argv[1]); out = pathlib.Path(sys.argv[2])
csv.field_size_limit(1 << 24)
airports = {}
with open(src / 'airports.csv', newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        if r['type'] not in ('large_airport', 'medium_airport'): continue
        if r['type'] == 'medium_airport' and r['scheduled_service'] != 'yes': continue
        try: lat, lon = float(r['latitude_deg']), float(r['longitude_deg'])
        except ValueError: continue
        airports[r['ident']] = dict(icao=r['ident'][:4], iata=(r['iata_code'] or '')[:3], lat=lat, lon=lon, rw=[])
with open(src / 'runways.csv', newline='', encoding='utf-8') as f:
    for r in csv.DictReader(f):
        a = airports.get(r['airport_ident'])
        if not a or r['closed'] == '1': continue
        try: la0, lo0, la1, lo1 = (float(r[k]) for k in ('le_latitude_deg', 'le_longitude_deg', 'he_latitude_deg', 'he_longitude_deg'))
        except ValueError: continue
        if r['surface'].upper().startswith(('WATER', 'GRS', 'TURF')) and r['type' if 'type' in r else 'surface'] : pass
        a['rw'].append((la0, lo0, la1, lo1, int(float(r['length_ft'] or 0))))
aps = sorted((a for a in airports.values() if a['rw']), key=lambda a: a['icao'])
rwl = []; lines = ['// generated by dev/gen_geodata.py from OurAirports (public domain) and Natural Earth 110m land (public domain)', '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>',
 'struct GeoAirport { int32_t lat, lon; char icao[5]; char iata[4]; uint16_t rwStart, rwCount; };', 'struct GeoRunway { int32_t lat0, lon0, lat1, lon1; uint16_t lengthFt; };']
ap_lines = []
for a in aps:
    ap_lines.append('{%d,%d,"%s","%s",%d,%d}' % (round(a['lat'] * 1e5), round(a['lon'] * 1e5), a['icao'], a['iata'], len(rwl), len(a['rw'])))
    for la0, lo0, la1, lo1, L in a['rw']: rwl.append('{%d,%d,%d,%d,%d}' % (round(la0 * 1e5), round(lo0 * 1e5), round(la1 * 1e5), round(lo1 * 1e5), min(L, 65535)))
lines.append('#define GEO_AIRPORT_COUNT %d' % len(ap_lines)); lines.append('static const GeoAirport GEO_AIRPORTS[] PROGMEM = {' + ',\n'.join(ap_lines) + '};')
lines.append('#define GEO_RUNWAY_COUNT %d' % len(rwl)); lines.append('static const GeoRunway GEO_RUNWAYS[] PROGMEM = {' + ',\n'.join(rwl) + '};')
# coastline: polygon rings as int16 (deg*100), simplified by dropping points closer than 0.35 deg
gj = json.load(open(src / 'ne_110m_land.json', encoding='utf-8'))
rings = []
for feat in gj['features']:
    g = feat['geometry']; polys = g['coordinates'] if g['type'] == 'MultiPolygon' else [g['coordinates']]
    for poly in polys:
        ring = poly[0]; pts = []; last = None
        for lon, lat in ring:
            if last is None or math.hypot(lon - last[0], lat - last[1]) >= 0.35: pts.append((lat, lon)); last = (lon, lat)
        if len(pts) >= 4: rings.append(pts)
pts_all = []; idx = []
for ring in rings: idx.append((len(pts_all), len(ring))); pts_all.extend(ring)
lines.append('#define GEO_COAST_RINGS %d' % len(idx)); lines.append('#define GEO_COAST_POINTS %d' % len(pts_all))
lines.append('static const uint16_t GEO_COAST_INDEX[][2] PROGMEM = {' + ','.join('{%d,%d}' % i for i in idx) + '};')
lines.append('static const int16_t GEO_COAST[][2] PROGMEM = {' + ','.join('{%d,%d}' % (round(la * 100), round(lo * 100)) for la, lo in pts_all) + '};')
out.write_text('\n'.join(lines) + '\n')
print(f'airports {len(ap_lines)}  runways {len(rwl)}  coast rings {len(idx)} points {len(pts_all)}  header {out.stat().st_size // 1024} KB')
